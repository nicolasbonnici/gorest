// commonPasswords is the screening list for Policy.Blocklist.
//
// It carries the entries that dominate every published breach corpus: the top
// leaked passwords, keyboard walks on QWERTY and AZERTY, first names, and the
// operational placeholders that reach production from a README (admin, root,
// changeme, test). Entries are stored lowercase; Policy also tests the
// leetspeak-folded form and strips trailing digits, so "P@ssw0rd2024" is
// caught by the single entry "password".
//
// This is deliberately a short curated list compiled into the binary rather
// than a multi-megabyte corpus. It is the difference between refusing the
// passwords that are actually guessed first and refusing every password an
// attacker has ever seen, and only the first belongs in a library's default.
// An application that needs the full corpus should screen against a service
// such as Pwned Passwords in its own registration hook.
